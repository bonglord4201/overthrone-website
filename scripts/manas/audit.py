# Audit of every OVERTHRONE Manas cosmetic (v14 stage 1): reads each sidecar JSON + its .bbmodel and reports what is
# really in the file: geometry, textures (render path the mod picks), animated textures, clips, the old "fx" cube
# particles, and the problems found. Writes minecraft/manas_cosmetics/AUDIT-V14.md.
#   python3 scripts/manas/audit.py
import json, glob, os, re, struct, zlib, collections
ROOT = os.path.join(os.path.dirname(__file__), '..', '..', 'minecraft', 'manas_cosmetics')
PREMIUM_V10 = {'celestial_sovereign'}   # sets whose helm/armour were rebuilt with the vox sculptor (premium.py)

def png_info(src):
    """(width, height, opaque px, partial px) of a base64 data-URI PNG, like BBModelParser.detectTranslucentAlpha."""
    import base64, io
    from PIL import Image
    b = base64.b64decode(src.split(',', 1)[1]); im = Image.open(io.BytesIO(b)).convert('RGBA')
    a = im.getchannel('A'); h = a.histogram()
    return im.width, im.height, sum(h[255:]), sum(h[1:255])

def walk(items, els, parent=None, out=None):
    out = [] if out is None else out
    for c in items:
        if isinstance(c, dict):
            out.append((c['name'], parent, [els[u] for u in c.get('children', []) if isinstance(u, str) and u in els]))
            walk(c.get('children', []), els, c['name'], out)
    return out

def model_report(path):
    m = json.load(open(path)); els = {e['uuid']: e for e in m['elements']}
    bones = walk(m['outliner'], els)
    tex = []
    for t in m.get('textures', []):
        w, h, op, part = png_info(t['source']); uvh = t.get('uv_height', m['resolution']['height'])
        mode = t.get('render_mode', 'default'); name = t['name']
        path_ = ('translucent' if part > op else 'cutout') + (' full-bright' if name.lower().replace('.png', '').endswith('_e') or mode in ('emissive', 'additive') else '')
        frames = h // uvh if (uvh and h > uvh and h % uvh == 0) else 1
        tex.append(dict(name=name, size='%dx%d' % (w, h), path=path_, frames=frames))
    fx_box = fx_plate = 0
    for name, parent, cubes in bones:
        if re.match(r'^.*s\d+$', name) and parent and re.sub(r's(\d+)$', r'\1', name) == parent:
            for e in cubes:
                d = [abs(e['to'][i] - e['from'][i]) for i in range(3)]
                if min(d) < 0.2: fx_plate += 1
                else: fx_box += 1
    clips = [(a['name'], a['length']) for a in m.get('animations', [])]
    return dict(cubes=len(m['elements']), bones=len(bones), tex=tex, fx_box=fx_box, fx_plate=fx_plate, clips=clips,
                animtex=sum(1 for t in tex if t['frames'] > 1))

def main():
    rows = collections.defaultdict(list)
    for f in sorted(glob.glob(os.path.join(ROOT, 'cosmetics', '*.json'))):
        d = json.load(open(f)); cid = d['id'].split(':')[1]; slot = d['slot']
        r = dict(id=cid, name=d.get('display_name', cid), slot=slot)
        if 'aura' in d: r['aura'] = d['aura']
        if d.get('model'): r['model'] = d['model']; r.update(model_report(os.path.join(ROOT, d['model'])))
        if 'particles' in d: r['wparticles'] = d['particles']
        rows[slot].append(r)
    L = ['# OVERTHRONE cosmetics audit (v14 stage 1)', '',
         'Generated by `scripts/manas/audit.py` from the real files in `minecraft/manas_cosmetics/` (what the server sends to players).',
         'It checks the files offline. It does not test them in game.', '',
         '## What the installed renderer can do (Manas Cosmetics 1.0.6, decompiled jar)',
         '- **Geometry:** cubes only, no meshes. Free rotations, nested bones. Every face is drawn from both sides.',
         '- **Texture render path:**',
         '  - a texture with more half-transparent than fully opaque pixels is drawn see-through (`TRANSLUCENT_TRANSPARENCY`, normal alpha blend)',
         '  - any other texture is cutout',
         '  - a name ending `_e`, or `render_mode` emissive/additive, is full-bright',
         '  - `render_mode: additive` is NOT additive blending in this version: it maps to cutout + full-bright (`BBModelRenderer.openPass`)',
         '- **Animated textures ARE supported** (`BBModelRenderer.computeUv`):',
         '  - a texture whose PNG height is a multiple of its `uv_height` plays its frames, one every `frame_time` ticks, looping',
         '  - frames sync to players (`SyncCosmeticRegistryPayload`)',
         '  - **none of our cosmetics used this before v14**',
         '- **Bone animation:**',
         '  - clips idle, walk, run, jump and fly are picked by player state; pets add special, special2 and swim',
         '  - linear keyframes on position, rotation and scale, plus Molang `math.sin`, `math.cos` and `query.anim_time`',
         '- **No particle emitters for model cosmetics:**',
         '  - "particles" can only be model pieces moved by keyframes',
         '  - weapons alone can send vanilla particles (`"particles"` on attack, use or charging)',
         '- **Auras** are drawn by the mod itself: 32 fixed styles and 10 particle shapes. They cannot carry a model.', '',
         '## Problems found and their cause', '']
    wings = rows['back']
    bad = [w for w in wings if w.get('fx_box', 0) > 0]
    L += ['- **Random floating cubes around the wings:**',
          '  - **Cause:** `wingkit.effects()` builds "particles" as tiny glowing **cubes** (`fx` bones) scattered at random positions, moving in straight lines.',
          '  - **Affected:** %d of %d wings, %d cubes in total.' % (len(bad), len(wings), sum(w['fx_box'] for w in bad)),
          '  - **Fix:** created incorrectly. Replace them with designed effects (v14).',
          '- **No flowing light anywhere:**',
          '  - **Cause:** the renderer supports animated textures, but none of our textures use them (0 animated textures in %d models).' % sum(1 for s in rows.values() for r in s if 'model' in r),
          '  - **Fix:** never created. Use them for travelling light streams, rune bands and pulsing glows.',
          '- **Auras falling behind and looking muddy:**',
          '  - **Cause:** `motion_response` above 0, plus pale or dark colours under the mod\'s alpha blending.',
          '  - **Status:** fixed in v13.',
          '- **Armour for 9 of 10 sets is the old v6 build:**',
          '  - **Cause:** only Celestial Sovereign was rebuilt with the vox sculptor (v10).',
          '  - **Fix:** never created.', '']
    def texs(r): return ', '.join('%s (%s%s)' % (t['size'], t['path'], ', %d frames' % t['frames'] if t['frames'] > 1 else '') for t in r['tex'])
    def mtable(title, items, extra=None):
        out = ['## ' + title + ' (%d)' % len(items), '', '| Cosmetic | Model | Cubes | Textures | Clips | Old cube particles | Animated textures | Problems |', '|---|---|---|---|---|---|---|---|']
        for r in items:
            probs = []
            if r.get('fx_box'): probs.append('%d random glowing cubes' % r['fx_box'])
            if not r.get('animtex'): probs.append('no flowing light (no animated textures)')
            if extra: probs += extra(r)
            clips = ' '.join(n for n, _ in r.get('clips', [])) or 'none'
            out.append('| %s `%s` | `%s` | %d | %s | %s | %d cubes, %d sprites | %d | %s |' % (r['name'], r['id'], r['model'].split('/')[-1], r['cubes'], texs(r), clips,
                       r.get('fx_box', 0), r.get('fx_plate', 0), r.get('animtex', 0), '; '.join(probs) or 'OK'))
        return out + ['']
    L += mtable('Wings and tails (back slot)', wings)
    L += mtable('Above-head: halos, crowns, horns, sigils', rows['above_head'])
    L += mtable('Helmets (set helms, crowns, horns)', rows['helmet'], lambda r: ['old v6 helm build'] if r['id'].endswith('_helm') and r['id'][:-5] not in PREMIUM_V10 else [])
    L += mtable('Orbit', rows['orbit'])
    L += mtable('Armour sets', rows['armor_set'], lambda r: ['old v6 armour build'] if r['id'][:-6] not in PREMIUM_V10 else [])
    L += mtable('Ground sigils', rows['ground'])
    L += mtable('Set weapons', rows['weapon'], lambda r: [] if 'wparticles' in r else ['no swing particles'])
    L += mtable('Pets', rows['pet'])
    L += ['## Auras (%d) and weapon auras (%d)' % (len(rows['aura']), len(rows['weapon_aura'])), '',
          'Drawn by the mod itself, so there is no model. The v13 rebuild gave every aura `motion_response` 0, its own style and palette, and solid particle shapes.', '',
          '| Aura | Style | Particle | Count | Stays with player |', '|---|---|---|---|---|']
    for r in rows['aura'] + rows['weapon_aura']:
        a = r['aura']; L.append('| %s `%s` | %s | %s | %s | %s |' % (r['name'], r['id'], a['style'], a['particle'], a.get('particle_count'), 'yes' if a.get('motion_response', 1) == 0 else '**NO**'))
    open(os.path.join(ROOT, 'AUDIT-V14.md'), 'w').write('\n'.join(L) + '\n')
    print('wings with cube particles: %d/%d; models: %d' % (len(bad), len(wings), sum(1 for s in rows.values() for r in s if 'model' in r)))

if __name__ == '__main__':
    main()
